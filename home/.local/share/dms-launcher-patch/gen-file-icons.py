#!/usr/bin/python3
"""Build the DMS launcher's per-file-type icons from VS Code's Material Icon Theme.

    usage: gen-file-icons.py

Output, next to this script:
  file-icons/*.svg   every icon the theme defines (hash suffix stripped)
  FileIcons.js       .pragma library lookup, copied into the DMS tree by
                     dms-launcher-patch (patch #18) and used by
                     ItemTransformers.transformFileResult.

The SVGs are COPIED, not referenced in place: a theme update renames its
extension folder (pkief.material-icon-theme-X.Y.Z), which would orphan every
path. Re-run this after updating the theme to pick up new icons.

Resolution order matches VS Code: exact file name > longest extension
("spec.ts" before "ts") > the language VS Code assigns to the extension
(that is how .py, .ts, .cs get their icons -- the theme keys those by
languageId, not by extension) > the generic file icon. Folders: exact name,
else the generic folder icon.
"""

import glob
import json
import os
import re
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, 'file-icons')
OUT_JS = os.path.join(HERE, 'FileIcons.js')
THEMES = sorted(glob.glob(os.path.expanduser(
    '~/.vscode/extensions/pkief.material-icon-theme-*/dist/material-icons.json')))
VSCODE_EXT = '/usr/share/code/resources/app/extensions'


def main():
    if not THEMES:
        raise SystemExit('Material Icon Theme not installed in VS Code')
    theme_json = THEMES[-1]
    theme_dir = os.path.dirname(theme_json)
    d = json.load(open(theme_json))

    # icon id -> clean svg file name, copied into OUT_DIR
    if os.path.isdir(OUT_DIR):
        shutil.rmtree(OUT_DIR)
    os.makedirs(OUT_DIR)
    files = {}
    for icon_id, spec in d['iconDefinitions'].items():
        src = os.path.normpath(os.path.join(theme_dir, spec['iconPath']))
        if not os.path.isfile(src):
            continue
        name = re.sub(r'~-?\d+(?=\.svg$)', '', os.path.basename(src))
        dst = os.path.join(OUT_DIR, name)
        if not os.path.exists(dst):
            shutil.copyfile(src, dst)
        files[icon_id] = name

    def ok(icon_id):
        return icon_id in files

    # VS Code's built-in language contributions: ext/filename -> languageId
    lang_ext, lang_name = {}, {}
    for pj in glob.glob(os.path.join(VSCODE_EXT, '*', 'package.json')):
        try:
            langs = json.load(open(pj)).get('contributes', {}).get('languages', [])
        except (OSError, ValueError):
            continue
        for lang in langs:
            lid = lang.get('id')
            for e in lang.get('extensions', []) or []:
                lang_ext.setdefault(e.lstrip('.').lower(), lid)
            for f in lang.get('filenames', []) or []:
                lang_name.setdefault(f.lower(), lid)

    by_lang = d.get('languageIds', {})
    exts, names = {}, {}
    for e, lid in lang_ext.items():
        if by_lang.get(lid) and ok(by_lang[lid]):
            exts[e] = by_lang[lid]
    for f, lid in lang_name.items():
        if by_lang.get(lid) and ok(by_lang[lid]):
            names[f] = by_lang[lid]
    # The theme's own keys win over the language fallback, as in VS Code.
    for e, i in d['fileExtensions'].items():
        if ok(i):
            exts[e.lower()] = i
    for f, i in d['fileNames'].items():
        if ok(i):
            names[f.lower()] = i
    folders = {f.lower(): i for f, i in d['folderNames'].items() if ok(i)}

    # Store file names, not ids, so the JS needs no second table.
    js = {
        'dir': OUT_DIR,
        'file': files.get(d['file'], ''),
        'folder': files.get(d['folder'], ''),
        'names': {k: files[v] for k, v in names.items()},
        'exts': {k: files[v] for k, v in exts.items()},
        'folders': {k: files[v] for k, v in folders.items()},
        'maxExtParts': max((k.count('.') + 1 for k in exts), default=1),
    }
    with open(OUT_JS, 'w') as fh:
        fh.write('.pragma library\n')
        fh.write('// GENERATED by gen-file-icons.py from %s -- do not edit.\n'
                 % os.path.basename(os.path.dirname(theme_dir)))
        fh.write('var T = %s;\n' % json.dumps(js, separators=(',', ':'), sort_keys=True))
        fh.write('''
// Absolute path of the icon for a file/folder base name, or "" if none.
function iconFor(name, isDir) {
    var n = String(name || "").toLowerCase();
    if (isDir)
        return T.dir + "/" + (T.folders[n] || T.folder);
    if (T.names[n])
        return T.dir + "/" + T.names[n];
    var parts = n.split(".");
    // "a.spec.ts" -> try "spec.ts", then "ts" (longest first, as VS Code).
    for (var k = Math.min(T.maxExtParts, parts.length - 1); k >= 1; k--) {
        var e = parts.slice(parts.length - k).join(".");
        if (T.exts[e])
            return T.dir + "/" + T.exts[e];
    }
    return T.file ? T.dir + "/" + T.file : "";
}
''')
    print('icons: %d svgs, %d names, %d exts, %d folders -> %s'
          % (len(os.listdir(OUT_DIR)), len(names), len(exts), len(folders), OUT_JS))


if __name__ == '__main__':
    main()
